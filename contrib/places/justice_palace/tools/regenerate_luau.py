#!/usr/bin/env python3
"""Rebuild SceneData.luau from scene_plan.json without Roblox/third-party dependencies."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]

def lua(v):
    if v is None:return 'nil'
    if isinstance(v,bool):return 'true' if v else 'false'
    if isinstance(v,str):return json.dumps(v,ensure_ascii=False)
    if isinstance(v,(int,float)):return json.dumps(v)
    if isinstance(v,list):return '{'+','.join(lua(x) for x in v)+'}'
    if isinstance(v,dict):return '{'+','.join('['+lua(k)+']='+lua(x) for k,x in v.items())+'}'
    raise TypeError(type(v).__name__)

def output():
    src=json.loads((ROOT/'scene_plan.json').read_text(encoding='utf8'))
    return '--!strict\n-- Generated from scene_plan.json; do not edit this file manually.\nreturn '+lua(src)+'\n'

if __name__=='__main__':
    (ROOT/'SceneData.luau').write_text(output(),encoding='utf8')
    print('Generated',ROOT/'SceneData.luau')
